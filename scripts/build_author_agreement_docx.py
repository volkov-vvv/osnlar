def set_run_font(run, size=11, bold=False, italic=False):
    run.bold = bold
    run.italic = italic
    run.font.size = Pt(size)
    run.font.name = "Times New Roman"
    r = run._element
    rPr = r.get_or_add_rPr()
    rFonts = rPr.get_or_add_rFonts()
    rFonts.set(qn("w:ascii"), "Times New Roman")
    rFonts.set(qn("w:hAnsi"), "Times New Roman")
    rFonts.set(qn("w:cs"), "Times New Roman")


def add_text(paragraph, text, size=11, bold=False, italic=False):
    run = paragraph.add_run(text)
    set_run_font(run, size=size, bold=bold, italic=italic)
    return run


def configure_paragraph(paragraph, *, align=WD_ALIGN_PARAGRAPH.JUSTIFY, space_after=6, first_line=True):
    paragraph.alignment = align
    pf = paragraph.paragraph_format
    pf.space_before = Pt(0)
    pf.space_after = Pt(space_after)
    pf.line_spacing_rule = WD_LINE_SPACING.SINGLE
    if first_line and align == WD_ALIGN_PARAGRAPH.JUSTIFY:
        pf.first_line_indent = Cm(1.25)
    else:
        pf.first_line_indent = Cm(0)


def p(doc, text, *, align=WD_ALIGN_PARAGRAPH.JUSTIFY, size=11, bold=False, space_after=6, first_line=True):
    paragraph = doc.add_paragraph()
    configure_paragraph(paragraph, align=align, space_after=space_after, first_line=first_line)
    add_text(paragraph, text, size=size, bold=bold)
    return paragraph


def p_parts(doc, parts, *, align=WD_ALIGN_PARAGRAPH.JUSTIFY, space_after=6, first_line=True):
    paragraph = doc.add_paragraph()
    configure_paragraph(paragraph, align=align, space_after=space_after, first_line=first_line)
    for text, bold in parts:
        add_text(paragraph, text, bold=bold)
    return paragraph


def heading(doc, text):
    return p(doc, text, align=WD_ALIGN_PARAGRAPH.CENTER, size=12, bold=True, space_after=10, first_line=False)


def page_break(doc):
    doc.add_page_break()


def fill_cell(cell, text, *, bold=False, align=WD_ALIGN_PARAGRAPH.LEFT):
    cell.text = ""
    lines = text.split("\n") if text else [""]
    for idx, line in enumerate(lines):
        paragraph = cell.paragraphs[0] if idx == 0 else cell.add_paragraph()
        configure_paragraph(paragraph, align=align, space_after=2, first_line=False)
        add_text(paragraph, line, bold=bold and idx == 0)


def set_table_borders(table, *, visible=True):
    tbl = table._tbl
    tblPr = tbl.tblPr if tbl.tblPr is not None else tbl._add_tblPr()
    old = tblPr.first_child_found_in("w:tblBorders")
    if old is not None:
        tblPr.remove(old)
    borders = OxmlElement("w:tblBorders")
    for edge in ("top", "left", "bottom", "right", "insideH", "insideV"):
        element = OxmlElement(f"w:{edge}")
        if visible:
            element.set(qn("w:val"), "single")
            element.set(qn("w:sz"), "4")
            element.set(qn("w:space"), "0")
            element.set(qn("w:color"), "000000")
        else:
            element.set(qn("w:val"), "nil")
            element.set(qn("w:sz"), "0")
            element.set(qn("w:space"), "0")
            element.set(qn("w:color"), "auto")
        borders.append(element)
    tblPr.append(borders)


def two_col_row(doc, left, right, *, bordered=False, left_bold=False, right_bold=False, right_align=WD_ALIGN_PARAGRAPH.LEFT):
    table = doc.add_table(rows=1, cols=2)
    table.autofit = True
    set_table_borders(table, visible=bordered)
    fill_cell(table.rows[0].cells[0], left, bold=left_bold)
    fill_cell(table.rows[0].cells[1], right, bold=right_bold, align=right_align)
    return table


def signature_block(doc, left_lines, right_lines):
    table = doc.add_table(rows=2, cols=2)
