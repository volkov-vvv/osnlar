    fill_cell(table.rows[0].cells[0], "Заказчик", bold=True)
    fill_cell(table.rows[0].cells[1], "Исполнитель", bold=True)
    fill_cell(table.rows[1].cells[0], left_lines)
    fill_cell(table.rows[1].cells[1], right_lines)
    return table


